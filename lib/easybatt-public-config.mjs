// Whitelist the public fields: internal costs and margins never leave the server API.
export function publicEasyBattConfig(config) {
  return {
    version: config.version,
    serviceRate: config.serviceRate,
    travelRate: config.travelRate,
    installationRate: config.installationRate,
    packagingWeightKgMl: config.packagingWeightKgMl,
    vat: config.vat,
    headquartersLabel: config.headquartersLabel,
    whatsappNumber: config.whatsappNumber,
    whatsappVerifyMessage: config.whatsappVerifyMessage,
    whatsappRecapMessage: config.whatsappRecapMessage,
    whatsappMessage: config.whatsappMessage,
    shippingBands: config.shippingBands.map(({ maxKg, price }) => ({ maxKg, price })),
    models: config.models.filter((model) => model.active !== false).map((model) => ({
      code: model.code,
      description: model.description,
      material: model.material,
      height: model.height,
      thickness: model.thickness,
      measure: model.measure,
      stickLengthLabel: model.stickLengthLabel,
      profile: model.profile,
      finish: model.finish,
      finishFamily: model.finishFamily,
      finishLabel: model.finishLabel,
      finishKey: model.finishKey,
      weightKgMl: model.weightKgMl,
      supplyPricePerMl: model.supplyBaseCostPerMl * (1 + config.supplyMargin),
      sectionImageUrl: model.sectionImageUrl,
      finishImageUrl: model.finishImageUrl,
      active: true,
    })),
  };
}
